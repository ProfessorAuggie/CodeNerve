// ───── Helper Functions ─────

export function getProblemById(id: string): Problem | undefined {
  return PROBLEMS.find((p) => p.id === id);
}

export function getProblemsByTopic(topicTag: string): Problem[] {
  return PROBLEMS.filter((p) => p.topicTags.includes(topicTag) && p.isActive);
}

export function getProblemsByPlatform(platform: string): Problem[] {
  return PROBLEMS.filter((p) => p.platform === platform && p.isActive);
}

export function getProblemsByDifficulty(difficulty: string): Problem[] {
  return PROBLEMS.filter((p) => p.difficulty === difficulty && p.isActive);
}

export function getProblemsByIds(ids: string[]): Problem[] {
  return ids
    .map((id) => PROBLEMS.find((p) => p.id === id))
    .filter((p): p is Problem => p !== undefined && p.isActive);
}

export function searchProblems(query: string): Problem[] {
  const q = query.toLowerCase();
  return PROBLEMS.filter(
    (p) =>
      p.isActive &&
      (p.title.toLowerCase().includes(q) ||
        p.topicTags.some((t) => t.includes(q)) ||
        p.platform.includes(q))
  );
}
